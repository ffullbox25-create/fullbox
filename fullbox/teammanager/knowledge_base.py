def get_knowledge_article(slug: str) -> KnowledgeArticle | None:
    key = str(slug or "").strip().lower()
    for article in KNOWLEDGE_ARTICLES:
        if article.slug == key:
            return article
    return None


def get_knowledge_document(key: str) -> dict[str, str] | None:
    return KNOWLEDGE_DOCUMENTS.get(str(key or "").strip().lower())


def list_knowledge_articles() -> list[KnowledgeArticle]:
    return list(KNOWLEDGE_ARTICLES)


def list_knowledge_sections() -> list[KnowledgeSection]:
    counts = {section.key: 0 for section in KNOWLEDGE_SECTIONS}
    for article in KNOWLEDGE_ARTICLES:
        counts[article.category] = counts.get(article.category, 0) + 1
    return [
        KnowledgeSection(
            section.key,
            section.title,
            section.description,
            section.icon,
            section.tags,
            counts.get(section.key, 0),
        )
        for section in KNOWLEDGE_SECTIONS
    ]


def list_knowledge_tags() -> list[str]:
    tags: set[str] = set()
    for section in KNOWLEDGE_SECTIONS:
        tags.update(section.tags)
    for article in KNOWLEDGE_ARTICLES:
        tags.update(article.tags)
    return sorted(tags)


def get_knowledge_section(key: str) -> KnowledgeSection | None:
    normalized = str(key or "").strip().lower()
    for section in list_knowledge_sections():
        if section.key == normalized:
            return section
    return None
