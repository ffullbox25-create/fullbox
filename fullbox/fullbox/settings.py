def _build_csrf_trusted_origins(raw: str) -> list[str]:
    origins: list[str] = []
    for item in raw.split(","):
        value = item.strip()
        if not value:
            continue
        if value.startswith("http://") or value.startswith("https://"):
            origins.append(value)
            continue
        # Behind TLS nginx / CDN we only need https; include http for bare local hosts.
        if value in {"127.0.0.1", "localhost"}:
            origins.append(f"http://{value}")
        origins.append(f"https://{value}")
    return origins


