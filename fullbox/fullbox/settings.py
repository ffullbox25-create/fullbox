def _redis_cache_location(redis_url: str) -> str:
    explicit_url = os.environ.get("REDIS_CACHE_URL", "").strip()
    if explicit_url:
        return explicit_url
    if not redis_url:
        return ""
    try:
        parsed = urlsplit(redis_url)
        if parsed.scheme not in {"redis", "rediss"}:
            return redis_url
        database = int(parsed.path.strip("/") or 0)
        return urlunsplit(parsed._replace(path=f"/{database + 1}"))
    except (TypeError, ValueError):
        return redis_url


